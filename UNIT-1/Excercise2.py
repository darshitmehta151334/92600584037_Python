# Different Data Types

a = 10          # Integer
b = 5.5         # Float
c = "Hello"     # String
d = True        # Boolean

print("Integer:", a)
print("Float:", b)
print("String:", c)
print("Boolean:", d)

# Type Casting

print("\nType Casting:")

x = float(a)      # int to float
y = int(b)        # float to int
z = str(a)        # int to string

print("Int to Float:", x)
print("Float to Int:", y)
print("Int to String:", z)
